const SUPPORTED_LANGS = ['es', 'en', 'ja', 'ko'];

function detectInitialLang(){
  try{
    const saved = localStorage.getItem('candy_lang');
    if(saved && I18N[saved]) return saved;
  }catch(e){}
  const nav = ((navigator.language || 'es').slice(0, 2)).toLowerCase();
  return SUPPORTED_LANGS.includes(nav) ? nav : 'es';
}

let LANG = detectInitialLang();

function t(key, params){
  const str = (I18N[LANG] && I18N[LANG][key]) || (I18N.es && I18N.es[key]) || key;
  if(!params) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
}

function wcName(id){ return t('wc.' + id + '.name'); }
function wcDesc(id){ return t('wc.' + id + '.desc'); }
function catLabel(cat){ return t('cat.' + cat); }
function skinLabel(key){ return t('skin.' + key); }
function trackLabel(key){ return t('track.' + key); }

function applyI18n(){
  document.documentElement.lang = LANG;
  document.title = t('app.title');
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-placeholder')); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
}

function setLang(l){
  if(!I18N[l]) return;
  LANG = l;
  try{ localStorage.setItem('candy_lang', l); }catch(e){}
  applyI18n();
  if(typeof populateMusicTrackOptions === 'function') populateMusicTrackOptions();
  if(typeof populateSkinOptions === 'function' && $('cfgSkin')) populateSkinOptions($('cfgSkin').value);
  if(typeof populateTimeSelect === 'function' && $('cfgActionTime')){
    populateTimeSelect('cfgActionTime', $('cfgActionTime').value || 30);
    populateTimeSelect('cfgPoisonTime', $('cfgPoisonTime').value || 20);
  }
  if(typeof game !== 'undefined' && game) renderCurrentPhase();
}
